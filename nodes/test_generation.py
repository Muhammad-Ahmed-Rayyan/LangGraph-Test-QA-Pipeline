from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

from state import AgentState, TestCaseSpec, TestSpec

TIMEOUT_SECONDS = 60

_FIELD_SAMPLE_VALUES = {
    "CharField": '"sample text"',
    "TextField": '"sample text"',
    "BooleanField": "True",
    "IntegerField": "1",
    "FloatField": "1.0",
    "EmailField": '"test@example.com"',
}

_INTROSPECT_SCRIPT = """
import django, json, os, sys
sys.path.insert(0, {root_dir!r})
os.environ.setdefault("DJANGO_SETTINGS_MODULE", {settings_module!r})
django.setup()
from django.apps import apps

out = []
for model in apps.get_app_config({app_label!r}).get_models():
    fields = []
    for f in model._meta.get_fields():
        if hasattr(f, "get_internal_type"):
            try:
                fields.append({{"name": f.name, "type": f.get_internal_type()}})
            except NotImplementedError:
                pass
    out.append({{"model": model.__name__, "fields": fields}})
print(json.dumps(out))
"""


def _find_settings_module(root_dir: Path) -> str | None:
    """Locate '<project_pkg>.settings' by finding the folder that has settings.py."""
    for settings_py in root_dir.rglob("settings.py"):
        pkg = settings_py.parent.name
        return f"{pkg}.settings"
    return None


def _introspect_app_models(python_exe: str, root_dir: Path, settings_module: str, app_label: str) -> list[dict]:
    script = _INTROSPECT_SCRIPT.format(
        root_dir=str(root_dir), settings_module=settings_module, app_label=app_label,
    )
    result = subprocess.run(
        [python_exe, "-c", script], cwd=str(root_dir),
        capture_output=True, text=True, timeout=TIMEOUT_SECONDS,
    )
    if result.returncode != 0:
        raise RuntimeError(f"Introspection failed for app '{app_label}':\n{result.stderr[-2000:]}")
    return json.loads(result.stdout)


def _build_spec(app: str, model_info: dict) -> TestSpec:
    cases: list[TestCaseSpec] = []
    for field in model_info["fields"]:
        if field["type"] in _FIELD_SAMPLE_VALUES:
            cases.append(TestCaseSpec(
                name=f"test_{field['name']}_round_trips",
                field=field["name"],
                checks=(
                    f"creating a {model_info['model']} with a sample "
                    f"{field['type']} value for '{field['name']}' and reading it back"
                ),
            ))
    return TestSpec(app=app, test_type="unit", target=model_info["model"], cases=cases)


def _render_test_file(spec: TestSpec, fields: list[dict]) -> str:
    known_types = {f["name"]: f["type"] for f in fields}
    lines = [
        "from django.test import TestCase",
        f"from .models import {spec['target']}",
        "",
        "",
        f"class {spec['target']}ModelTests(TestCase):",
        '    """Auto-generated by the CodeMinds Testing Agent. Review before relying on these."""',
        "",
    ]
    for case in spec["cases"]:
        sample = _FIELD_SAMPLE_VALUES[known_types[case["field"]]]
        lines += [
            f"    def {case['name']}(self):",
            f"        obj = {spec['target']}.objects.create({case['field']}={sample})",
            "        obj.refresh_from_db()",
            f"        self.assertEqual(obj.{case['field']}, {sample})",
            "",
        ]
    if not spec["cases"]:
        lines += [
            "    def test_can_be_created(self):",
            f"        obj = {spec['target']}.objects.create()",
            "        self.assertIsNotNone(obj.pk)",
            "",
        ]
    return "\n".join(lines) + "\n"


def test_generation_node(state: AgentState) -> AgentState:
    if state.get("status") != "ready_for_test_generation":
        return state

    project = state["project"]
    root_dir = Path(project["root_dir"])
    venv_bin = "Scripts" if sys.platform == "win32" else "bin"
    venv_python = str((root_dir.parent / f"_venv_{root_dir.name}" / venv_bin / "python").resolve())

    settings_module = _find_settings_module(root_dir)
    if settings_module is None:
        raise RuntimeError("Could not locate settings.py to introspect models")

    test_specs: list[TestSpec] = []
    test_files: dict[str, str] = {}

    for app in project["django_apps"]:
        models_info = _introspect_app_models(venv_python, root_dir, settings_module, app)
        for model_info in models_info:
            spec = _build_spec(app, model_info)
            test_specs.append(spec)

            content = _render_test_file(spec, model_info["fields"])
            rel_path = f"{app}/tests_generated.py"
            test_files[rel_path] = content
            (root_dir / rel_path).write_text(content)

    return {
        **state,
        "test_specs": test_specs,
        "test_files": test_files,
    }