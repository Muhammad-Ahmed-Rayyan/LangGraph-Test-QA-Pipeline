"""
Stage 7 — Deployment artifacts node.

Runs right after the production readiness checks. It writes the files a person would
need to ship the project in a container, built from what the checks found:

  Dockerfile, .dockerignore, docker-compose.yml, .env.example and DEPLOYMENT.md

They go to reports/<project>_deployment/. The node never changes the project's own
files, and never builds or starts anything. Every artifact is checked statically (the
files it names must exist), and the result is recorded in report["production"].

Secret values are never copied into any artifact: .env.example holds placeholders.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import nodes.report as report_module
from nodes.env_utils import find_settings_module
from nodes.report import write_report
from state import AgentState

_WEB_SERVER_PACKAGES = {"wsgi": "gunicorn", "asgi": "uvicorn"}
_SYSTEM_PACKAGES = {
    "psycopg2": ["build-essential", "libpq-dev"],          # the non-binary build compiles against libpq
    "mysqlclient": ["build-essential", "default-libmysqlclient-dev", "pkg-config"],
}
_POSTGRES_PACKAGES = {"psycopg2", "psycopg2-binary", "psycopg", "psycopg-binary"}


def _deployment_dir(project_name: str) -> Path:
    return Path(report_module.__file__).resolve().parents[1] / "reports" / f"{project_name}_deployment"


def _requirement_names(requirements_file: str | None) -> set[str]:
    if not requirements_file:
        return set()
    try:
        lines = Path(requirements_file).read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return set()
    names = set()
    for raw in lines:
        line = raw.split("#", 1)[0].strip()
        if line and not line.startswith(("-", "git+", "http")):
            names.add(re.split(r"[=<>~!\[;\s]", line, maxsplit=1)[0].lower().replace("_", "-"))
    return names


def _relative_module(module: str, workdir: Path) -> str:
    """The module name as seen from the folder that holds manage.py."""
    prefix = list(workdir.parts)
    parts = module.split(".")
    return ".".join(parts[len(prefix):]) if prefix and parts[:len(prefix)] == prefix else module


def _settings_read_environment(root: Path) -> bool:
    module = find_settings_module(root)
    if not module:
        return False
    path = root.joinpath(*module.split(".")).with_suffix(".py")
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    return bool(re.search(r"\b(?:os\.environ|os\.getenv|getenv|environ|env\()", text))


# --- the artifacts ------------------------------------------------------------


def _dockerfile(requirements: str, workdir: str, command: list[str], extra_pip: list[str], system_packages: list[str]) -> str:
    lines = [
        "# Generated by the Testing/QA agent from the project's own files.",
        "# It was checked statically (every file it names exists) but never built. Review it before use.",
        "FROM python:3.12-slim",
        "",
        "ENV PYTHONDONTWRITEBYTECODE=1 \\",
        "    PYTHONUNBUFFERED=1",
        "",
        "WORKDIR /app",
        "",
    ]
    if system_packages:
        lines += ["RUN apt-get update \\",
                  f"    && apt-get install -y --no-install-recommends {' '.join(system_packages)} \\",
                  "    && rm -rf /var/lib/apt/lists/*", ""]
    lines += [f"COPY {requirements} /app/{requirements}", f"RUN pip install --no-cache-dir -r /app/{requirements}"]
    if extra_pip:
        lines.append(f"RUN pip install --no-cache-dir {' '.join(extra_pip)}")
    lines += ["", "COPY . /app"]
    if workdir:
        lines.append(f"WORKDIR /app/{workdir}")
    lines += ["", "RUN useradd --create-home --uid 1000 app && chown -R app:app /app", "USER app", "",
              "EXPOSE 8000", f"CMD {json.dumps(command)}"]
    return "\n".join(lines) + "\n"


def _dockerignore() -> str:
    return "\n".join([
        ".git", "__pycache__/", "*.pyc", "venv/", ".venv/", "_venv_*/", "*_extracted/", "db.sqlite3",
        ".env", ".env.*", "node_modules/", "media/",
        "# Test files written by the Testing/QA agent are not part of the release.",
        "**/tests_generated.py", "**/tests_integration_generated.py", "**/tests_system_generated.py",
        "**/test_settings.py", "",
    ])


def _compose(has_postgres: bool) -> str:
    lines = ["# Generated by the Testing/QA agent. Review it before use.", "services:", "  web:", "    build: .",
             "    env_file: .env", "    ports:", '      - "8000:8000"']
    if has_postgres:
        lines += ["    depends_on:", "      db:", "        condition: service_healthy",
                  "  db:", "    image: postgres:16", "    env_file: .env", "    volumes:", "      - db_data:/var/lib/postgresql/data",
                  "    healthcheck:", '      test: ["CMD-SHELL", "pg_isready -U $${POSTGRES_USER} -d $${POSTGRES_DB}"]',
                  "      interval: 5s", "      timeout: 5s", "      retries: 10",
                  "", "volumes:", "  db_data:"]
    return "\n".join(lines) + "\n"


def _env_example(has_postgres: bool) -> str:
    lines = ["# Copy this file to .env and fill in real values. Never commit the real .env file.",
             "DJANGO_SECRET_KEY=replace-with-a-long-random-value", "DJANGO_DEBUG=0",
             "DJANGO_ALLOWED_HOSTS=localhost,127.0.0.1"]
    if has_postgres:
        lines += ["POSTGRES_DB=app", "POSTGRES_USER=app", "POSTGRES_PASSWORD=replace-me",
                  "DATABASE_URL=postgres://app:replace-me@db:5432/app"]
    return "\n".join(lines) + "\n"


def _checklist(production: dict, name: str, reads_environment: bool, has_dockerfile: bool, has_postgres: bool) -> str:
    findings = production.get("findings", [])
    blocking = [f for f in findings if f["severity"] == "high"]
    warnings = [f for f in findings if f["severity"] != "high"]
    lines = [f"# Deployment checklist: {name}", "",
             f"Verdict: **{production.get('verdict', 'unknown')}**. Generated by the Testing/QA agent. "
             "Nothing here was built or deployed.", ""]
    lines += ["## Fix before deploying", ""]
    lines += [f"- [ ] {f['id']}: {f['message']}" for f in blocking] or ["- [x] No blocking findings."]
    lines += ["", "## Worth fixing", ""]
    lines += [f"- [ ] {f['id']} ({f['severity']}): {f['message']}" for f in warnings] or ["- [x] Nothing else was found."]
    lines += ["", "## Settings the generated files expect", ""]
    if reads_environment:
        lines.append("- [ ] The settings already read the environment. Check that they use `DJANGO_SECRET_KEY`, "
                     "`DJANGO_DEBUG` and `DJANGO_ALLOWED_HOSTS` (the names in `.env.example`), or rename them there.")
    else:
        lines.append("- [ ] The settings do not read the environment. Change them to read `DJANGO_SECRET_KEY`, "
                     "`DJANGO_DEBUG` and `DJANGO_ALLOWED_HOSTS` from it, or `.env` has no effect.")
    if has_postgres:
        lines.append("- [ ] Point the database setting at `DATABASE_URL` (or the `POSTGRES_*` values) so the "
                     "`db` service in the compose file is used.")
    if has_dockerfile:
        lines += ["", "## First deploy", "",
                  "1. `copy .env.example .env` (or `cp`) and fill in real values.",
                  "2. `docker compose build`",
                  "3. Back up the database, then `docker compose run --rm web python manage.py migrate`",
                  "4. `docker compose run --rm web python manage.py collectstatic --noinput` "
                  "(needs `STATIC_ROOT` set, and a web server or WhiteNoise to serve the files)",
                  "5. `docker compose up -d`"]
    lines += ["", "## Rollback", "",
              "- [ ] Tag every image you deploy, and keep the previous tag.",
              "- [ ] To roll back code, redeploy the previous tag.",
              "- [ ] Migrations are not undone by redeploying old code. Before a migration that removes or "
              "renames a column, take a database backup, and know the command that reverses it "
              "(`python manage.py migrate <app> <previous migration>`).", ""]
    return "\n".join(lines)


# --- checks and node ----------------------------------------------------------


def _static_checks(root: Path, manage_py: Path, requirements: str | None, base: Path, module: str | None) -> list[dict]:
    checks = [{"check": "manage.py exists", "ok": manage_py.is_file()}]
    if requirements:
        checks.append({"check": f"{requirements} exists (named by the Dockerfile)", "ok": (root / requirements).is_file()})
    if module:
        module_file = base.joinpath(*module.split(".")).with_suffix(".py")
        checks.append({"check": f"entry point {module} exists", "ok": module_file.is_file()})
    else:
        checks.append({"check": "an entry point (wsgi.py or asgi.py) exists", "ok": False})
    return checks


def deployment_artifacts_node(state: AgentState) -> AgentState:
    """
    LangGraph node. Reads report_json["production"] and the project, writes the files
    into reports/<project>_deployment/, and records them in report_json["production"].
    """
    report = state.get("report_json") or {}
    production = report.get("production")
    project = state.get("project") or {}
    if not production or not project.get("is_django_project") or not project.get("manage_py_path"):
        return state

    root = Path(project["root_dir"]).resolve()
    manage_py = Path(project["manage_py_path"]).resolve()
    workdir = manage_py.parent.relative_to(root) if manage_py.parent != root and root in manage_py.parents else Path(".")
    entrypoint = production.get("entrypoint", {})
    kind = "wsgi" if entrypoint.get("wsgi") else ("asgi" if entrypoint.get("asgi") else None)
    module = _relative_module(entrypoint[kind], workdir) if kind else None

    names = _requirement_names(project.get("requirements_file"))
    requirements = None
    if project.get("requirements_file"):
        try:
            requirements = Path(project["requirements_file"]).resolve().relative_to(root).as_posix()
        except ValueError:
            requirements = None
    has_postgres = bool(names & _POSTGRES_PACKAGES)
    reads_environment = _settings_read_environment(root)

    files: dict[str, str] = {}
    if kind and requirements:
        server = _WEB_SERVER_PACKAGES[kind]
        command = (["gunicorn", f"{module}:application", "--bind", "0.0.0.0:8000"] if kind == "wsgi"
                   else ["uvicorn", f"{module}:application", "--host", "0.0.0.0", "--port", "8000"])
        system_packages = sorted({pkg for name, pkgs in _SYSTEM_PACKAGES.items() if name in names for pkg in pkgs})
        files["Dockerfile"] = _dockerfile(requirements, workdir.as_posix() if str(workdir) != "." else "",
                                          command, [] if server in names else [server], system_packages)
        files[".dockerignore"] = _dockerignore()
        files["docker-compose.yml"] = _compose(has_postgres)
        files[".env.example"] = _env_example(has_postgres)
    files["DEPLOYMENT.md"] = _checklist(production, root.name, reads_environment, "Dockerfile" in files, has_postgres)

    target = _deployment_dir(root.name)
    target.mkdir(parents=True, exist_ok=True)
    for file_name, content in files.items():
        (target / file_name).write_text(content, encoding="utf-8")

    checks = _static_checks(root, manage_py, requirements, root / workdir, module)
    checks.append({"check": "every artifact was written", "ok": all((target / n).is_file() for n in files)})
    new_production = {
        **production,
        "artifacts": [{"file": name, "path": f"reports/{root.name}_deployment/{name}"} for name in files],
        "artifact_checks": checks,
    }
    new_report = {**report, "production": new_production}
    write_report(new_report, root.name)
    return {**state, "report_json": new_report, "production_report": new_production}
